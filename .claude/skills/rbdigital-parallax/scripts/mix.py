#!/usr/bin/env python3
"""Mix video + music + SFX + VO lines (music ducks under the VO). Works with or without VO.
Usage: python3 mix.py video.mp4 music.(wav|mp3) out.mp4 DURATION [--sfx events.json] [vo1.wav:0.4 vo2.wav:5.3 ...]
- music: generated by music.py or their own file (looped if shorter than the video)
- --sfx: events.json written by render.py (whoosh/paper on transitions, pop on captions, chime on tagline)
- each VO arg is file:start_seconds (vo_args.txt from plan_scenes.py has them ready)"""
import sys, os, subprocess, tempfile
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__))); import sfx as SFX, json
args = sys.argv[1:]; sfx_file = None
if "--sfx" in args: i = args.index("--sfx"); sfx_file = args[i+1]; del args[i:i+2]
v, m, out, dur = args[:4]; dur = float(dur); vos = [a.rsplit(":", 1) for a in args[4:]]
inp = ["-i", v, "-stream_loop", "-1", "-i", m]; fc = []; n = 2
music_vol = .25 if vos else .8
fc.append(f"[1]atrim=0:{dur},volume={music_vol},afade=t=in:d=0.5,afade=t=out:st={max(0, dur-1.5)}:d=1.5[m]")
if sfx_file:
    tmp = os.path.join(tempfile.gettempdir(), "sfx_track.wav"); SFX.save(SFX.build(json.load(open(sfx_file)), dur), tmp)
    inp += ["-i", tmp]; fc.append(f"[{n}]volume=1[sx]"); n += 1
if vos:
    labels = ""
    for k, (f, s) in enumerate(vos):
        inp += ["-i", f]; ms = int(float(s)*1000); fc.append(f"[{n}]adelay={ms}|{ms}[v{k}]"); labels += f"[v{k}]"; n += 1
    fc.append(f"{labels}amix=inputs={len(vos)}:normalize=0,acompressor=threshold=0.1:ratio=3:makeup=2,loudnorm=I=-15:TP=-1.5[vo]")
    fc += ["[vo]asplit[a][b]", "[m][a]sidechaincompress=threshold=0.04:ratio=5:release=350[md]"]
    mixin = "[md][b]" + ("[sx]" if sfx_file else ""); k = 2+(1 if sfx_file else 0)
else:
    mixin = "[m]" + ("[sx]" if sfx_file else ""); k = 1+(1 if sfx_file else 0)
fc.append(f"{mixin}amix=inputs={k}:normalize=0:duration=longest,alimiter=limit=0.95[aout]" if k > 1 else f"{mixin}alimiter=limit=0.95[aout]")
subprocess.run(["ffmpeg", "-y", "-loglevel", "error", *inp, "-filter_complex", ";".join(fc), "-map", "0:v", "-map", "[aout]",
                "-c:v", "copy", "-c:a", "aac", "-b:a", "192k", "-ar", "44100", "-t", str(dur), "-movflags", "+faststart", out], check=True)
print("OK", out)
